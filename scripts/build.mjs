#!/usr/bin/env node
// Generates every agent format from the single source of truth in rules/.
//
//   node scripts/build.mjs           write outputs
//   node scripts/build.mjs --check   fail if any output is missing or stale (CI)
//
// Outputs (all committed, so agents and the Claude Code marketplace can install
// straight from the repository):
//   audit/rules-index.json, audit/CHECKLIST.md
//   skills/ui-polish/SKILL.md, skills/ui-audit/SKILL.md      (Claude Code plugin, repo root is the plugin)
//   .claude-plugin/plugin.json, .claude-plugin/marketplace.json
//   dist/agents-md/AGENTS.md                                 (Codex and any AGENTS.md reader)
//   dist/gemini/GEMINI.md
//   dist/copilot/.github/copilot-instructions.md
//   dist/cursor/.cursor/rules/*.mdc
//   dist/windsurf/.windsurf/rules/*.md                       (also installed to .devin/rules)
//   dist/claude-project/.claude/skills/*/SKILL.md            (project-skill install without the plugin)

import fs from 'node:fs';
import path from 'node:path';
import process from 'node:process';
import { fileURLToPath, pathToFileURL } from 'node:url';
import { STATIC_RULE_IDS } from '../audit/lib/run.mjs';

export const ROOT = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
export const MARK_START = '<!-- ui-polish-kit:start (generated by ui-polish-kit; edit the rules in that repo, not this block) -->';
export const MARK_END = '<!-- ui-polish-kit:end -->';

const SEVERITIES = ['error', 'warning', 'info'];
const CHECKS = ['static', 'visual', 'process'];
const PARTS = ['Rule', 'Why', 'Bad', 'Good', 'Check'];

/** Size ceilings per output kind, in characters. Always-on files are loaded into every prompt. */
export const LIMITS = { alwaysOn: 12000, windsurfFile: 6000, cursorLines: 500, codexBytes: 32 * 1024, skillDescription: 1536 };

// ---------------------------------------------------------------------------
// Parse rules/
// ---------------------------------------------------------------------------

function parseFrontmatter(src, file) {
  const m = /^---\r?\n([\s\S]*?)\r?\n---\r?\n/.exec(src);
  if (!m) throw new Error(`${file}: missing frontmatter`);
  const data = {};
  for (const line of m[1].split(/\r?\n/)) {
    const kv = /^([\w-]+):\s*(.*)$/.exec(line);
    if (!kv) throw new Error(`${file}: bad frontmatter line "${line}"`);
    data[kv[1]] = kv[2].trim();
  }
  return { data, body: src.slice(m[0].length) };
}

export function parseTopic(src, file) {
  const { data, body } = parseFrontmatter(src.replace(/\r\n/g, '\n'), file);
  for (const key of ['topic', 'prefix', 'title', 'when']) if (!data[key]) throw new Error(`${file}: frontmatter needs "${key}"`);
  if (!/^[A-Z]{2}$/.test(data.prefix)) throw new Error(`${file}: prefix must be two capital letters`);

  const rules = [];
  const errors = [];
  // Split only at rule headings: example code may itself contain "## " lines.
  const sections = body.split(/^(?=## [A-Z]{2}-\d{2} · )/m);
  const intro = sections.shift();
  for (const stray of body.replace(/```[\s\S]*?```/g, '').match(/^## (?![A-Z]{2}-\d{2} · ).*$/gm) || []) {
    errors.push(`heading must be "## XX-00 · Title": ${stray}`);
  }
  if (!/^# .+/m.test(intro)) errors.push('missing "# Title" heading and introduction');

  for (const section of sections) {
    const head = /^## ([A-Z]{2}-\d{2}) · (.+)\n(.*)\n/.exec(section);
    if (!head) { errors.push(`heading must be "## XX-00 · Title": ${section.split('\n')[0]}`); continue; }
    const [, id, title, metaLine] = head;
    const meta = /^Severity: (\w+) · Check: (\w+)$/.exec(metaLine.trim());
    if (!meta) { errors.push(`${id}: the line under the heading must be "Severity: error|warning|info · Check: static|visual|process"`); continue; }
    if (!id.startsWith(`${data.prefix}-`)) errors.push(`${id}: does not match topic prefix ${data.prefix}`);
    if (!SEVERITIES.includes(meta[1])) errors.push(`${id}: unknown severity ${meta[1]}`);
    if (!CHECKS.includes(meta[2])) errors.push(`${id}: unknown check type ${meta[2]}`);

    const parts = {};
    let last = -1;
    PARTS.forEach((name, i) => {
      const at = section.indexOf(`**${name}.**`);
      if (at < 0) { errors.push(`${id}: missing **${name}.**`); return; }
      if (at < last) errors.push(`${id}: **${name}.** is out of order (Rule, Why, Bad, Good, Check)`);
      last = at;
      const next = PARTS.slice(i + 1).map((n) => section.indexOf(`**${n}.**`)).find((p) => p > at);
      let text = section.slice(at + name.length + 5, next === undefined ? section.length : next);
      if (name === 'Check') text = text.split(/\n### /)[0];
      parts[name] = text.trim();
      if (!parts[name]) errors.push(`${id}: **${name}.** is empty`);
    });
    for (const name of ['Bad', 'Good']) {
      if (parts[name] && !/```[\s\S]+```/.test(parts[name])) errors.push(`${id}: **${name}.** needs a fenced code example`);
    }
    if (parts.Rule && parts.Rule.length > 900) errors.push(`${id}: **Rule.** is ${parts.Rule.length} characters; keep it under 900 (detail belongs in Why/Check)`);
    rules.push({ id, title: title.trim(), severity: meta[1], check: meta[2], rule: (parts.Rule || '').replace(/\s+/g, ' '), parts });
  }
  if (!rules.length) errors.push('no rules found');
  const ids = rules.map((r) => r.id);
  ids.forEach((id, i) => {
    if (ids.indexOf(id) !== i) errors.push(`${id}: duplicate rule ID`);
    const n = Number(id.slice(3));
    if (n !== i + 1) errors.push(`${id}: rules must be numbered in order without gaps (expected ${data.prefix}-${String(i + 1).padStart(2, '0')})`);
  });
  if (errors.length) throw new Error(`${file}:\n  - ${errors.join('\n  - ')}`);
  return { ...data, file, intro: intro.trim(), rules, source: src };
}

export function loadTopics(root = ROOT) {
  const dir = path.join(root, 'rules');
  const files = fs.readdirSync(dir).filter((f) => /^\d{2}-[\w-]+\.md$/.test(f)).sort();
  const topics = files.map((f) => parseTopic(fs.readFileSync(path.join(dir, f), 'utf8'), f));
  const prefixes = topics.map((t) => t.prefix);
  const dup = prefixes.find((p, i) => prefixes.indexOf(p) !== i);
  if (dup) throw new Error(`Two topics share the prefix ${dup}`);

  // Cross-checks between rules/ and the checker and recipes.
  const all = new Map(topics.flatMap((t) => t.rules.map((r) => [r.id, r])));
  const problems = [];
  for (const id of STATIC_RULE_IDS) {
    if (!all.has(id)) problems.push(`checker emits ${id} but no rule file defines it`);
    else if (all.get(id).check !== 'static') problems.push(`${id} is emitted by the checker but marked "Check: ${all.get(id).check}"`);
  }
  for (const [id, r] of all) {
    if (r.check === 'static' && !STATIC_RULE_IDS.includes(id)) problems.push(`${id} is marked "Check: static" but the checker has no detector for it (audit/lib/run.mjs STATIC_RULE_IDS)`);
  }
  for (const t of topics) {
    for (const m of t.source.matchAll(/`((?:recipes|templates|audit)\/[\w./-]+\.\w+)`/g)) {
      if (!fs.existsSync(path.join(root, m[1]))) problems.push(`${t.file} points to ${m[1]}, which does not exist`);
    }
    for (const m of t.source.matchAll(/\b([A-Z]{2}-\d{2})\b/g)) {
      if (!all.has(m[1])) problems.push(`${t.file} mentions ${m[1]}, which is not a rule`);
    }
  }
  if (problems.length) throw new Error(`Rule cross-check failed:\n  - ${[...new Set(problems)].join('\n  - ')}`);
  return topics;
}

// ---------------------------------------------------------------------------
// Render
// ---------------------------------------------------------------------------

const yaml = (s) => JSON.stringify(s); // a JSON string is a valid YAML double-quoted scalar
const bare = (s) => ({ bare: s }); // enum values that must not be quoted

function frontmatter(fields) {
  const lines = Object.entries(fields).map(([k, v]) => `${k}: ${typeof v === 'string' ? yaml(v) : v && v.bare ? v.bare : v}`);
  return `---\n${lines.join('\n')}\n---\n`;
}

function renderCore(root, topics, { kit, topicPath, compactTopics = false }) {
  const core = fs.readFileSync(path.join(root, 'rules', '_core.md'), 'utf8').replace(/\r\n/g, '\n').trim();
  const table = compactTopics
    ? topics.map((t) => `- ${t.prefix} ${t.title}: \`${topicPath(t)}\``).join('\n')
    : ['| Topic | File | Read it when |', '| --- | --- | --- |', ...topics.map((t) => `| ${t.prefix} ${t.title} | \`${topicPath(t)}\` | ${t.when} |`)].join('\n');
  if (!core.includes('{{TOPICS}}') || !core.includes('{{KIT}}')) throw new Error('rules/_core.md must contain {{KIT}} and {{TOPICS}}');
  return core.replace('{{TOPICS}}', table).replaceAll('{{KIT}}', kit);
}

function digest(topic, fullPath) {
  const lines = [
    `# ${topic.title} (${topic.prefix})`,
    '',
    `This is the short form. Before writing code in this area, read the full rules with reasons, bad/good examples and checks: \`${fullPath}\`.`,
    '',
    ...topic.rules.map((r) => `- **${r.id} ${r.title}** (${r.severity}). ${r.rule}`),
  ];
  return `${lines.join('\n')}\n`;
}

function auditStub(kit) {
  return [
    '# UI audit',
    '',
    `Follow the procedure in \`${kit}/audit/PROCEDURE.md\` exactly. In short:`,
    '',
    `1. Static check: \`node ${kit}/audit/cli.mjs .\` (add \`--json\` for machine output). Record the score.`,
    `2. Start the app and capture every page in scope at 375, 768 and 1440px, in light and dark: \`node ${kit}/audit/screenshot.mjs <url>\` or your browser tool. Capture open dropdowns, date pickers and dialogs, and the empty, loading and error states. Look at every image.`,
    '3. Walk the 29-item visual checklist in the procedure; mark pass, fail or n/a. Blocker items fail the audit on their own.',
    '4. Keyboard pass, form pass, resize pass.',
    '5. Score: static score from the checker; visual score = passed / (passed + failed). PASS needs a passing static check, no failed blocker and a visual score of at least 90.',
    '6. Fix: design.md and tokens first, then errors and blockers, then warnings. Fix causes; do not weaken the config or add ignores without a reason.',
    '7. Re-run the checker, re-capture, repeat until PASS or the remainder needs the owner.',
    '8. Report: scores before and after, fixed, remaining, assumptions and suppressions, not verified.',
    '',
    `Every rule ID is explained in \`${kit}/rules/\`; the one-page list is \`${kit}/audit/CHECKLIST.md\`.`,
    '',
  ].join('\n');
}

function checklist(topics) {
  const out = [
    '# Checklist: every rule',
    '',
    'Generated from `rules/` by `scripts/build.mjs`. Do not edit. `static` rules are reported by `audit/cli.mjs`; `visual` rules are checked against screenshots and the running app; `process` rules are about how the work is done. Details for each ID are in the topic file.',
    '',
  ];
  for (const t of topics) {
    out.push(`## ${t.prefix} · ${t.title} (\`rules/${t.file}\`)`, '');
    for (const r of t.rules) out.push(`- [ ] **${r.id}** (${r.severity}, ${r.check}) ${r.title}`);
    out.push('');
  }
  return out.join('\n');
}

const SKILL_POLISH = 'Design-quality rules for building or changing any user interface: web pages, React/Tailwind/shadcn components, forms, dashboards, landing pages, stylesheets and UI copy. Use before writing UI code so the result uses design tokens, themed controls (no browser-default selects, date pickers or file inputs), deliberate typography, consistent spacing, complete component states, dark mode and accessibility instead of generic AI-looking defaults.';
const SKILL_AUDIT = 'Audit an interface: run the ui-polish static checker, screenshot the running app at mobile, tablet and desktop widths in light and dark, walk the checklist, score it, fix failures and re-check. Use when asked to review, audit, polish or QA a UI, when a UI looks generic or unfinished, and before reporting any UI task as done.';

export function buildOutputs(root = ROOT) {
  const topics = loadTopics(root);
  const pkg = JSON.parse(fs.readFileSync(path.join(root, 'package.json'), 'utf8'));
  const out = new Map();
  const put = (rel, content) => out.set(rel, content.endsWith('\n') ? content : `${content}\n`);

  // --- machine index + checklist
  const index = {
    version: pkg.version,
    topics: topics.map((t) => ({ prefix: t.prefix, topic: t.topic, title: t.title, file: t.file, when: t.when })),
    rules: Object.fromEntries(topics.flatMap((t) => t.rules.map((r) => [r.id, { title: r.title, severity: r.severity, check: r.check, topic: t.topic, file: t.file }]))),
  };
  put('audit/rules-index.json', JSON.stringify(index, null, 2));
  put('audit/CHECKLIST.md', checklist(topics));

  const KIT = '.ui-polish';
  const generic = renderCore(root, topics, { kit: KIT, topicPath: (t) => `${KIT}/rules/${t.file}` });
  const block = `${MARK_START}\n${generic}\n${MARK_END}`;

  // --- AGENTS.md (Codex, and every agent that reads AGENTS.md), GEMINI.md, Copilot
  put('dist/agents-md/AGENTS.md', block);
  put('dist/gemini/GEMINI.md', block);
  put('dist/copilot/.github/copilot-instructions.md', block);

  // --- Cursor: one always-on rule, one "Apply Intelligently" rule per topic
  put('dist/cursor/.cursor/rules/ui-polish-kit.mdc', `${frontmatter({ description: 'UI polish core rules: always apply when building or changing interface code.', alwaysApply: true })}\n${generic}`);
  for (const t of topics) {
    put(`dist/cursor/.cursor/rules/ui-polish-${t.file.replace(/\.md$/, '')}.mdc`, `${frontmatter({ description: `${t.title} rules (ui-polish-kit). ${t.when}`, alwaysApply: false })}\n${digest(t, `${KIT}/rules/${t.file}`)}`);
  }
  put('dist/cursor/.cursor/rules/ui-polish-audit.mdc', `${frontmatter({ description: `UI audit procedure (ui-polish-kit). ${SKILL_AUDIT}`, alwaysApply: false })}\n${auditStub(KIT)}`);

  // --- Windsurf / Devin Desktop: always_on core (compact), model_decision topics
  const windsurfCore = renderCore(root, topics, { kit: KIT, topicPath: (t) => `${KIT}/rules/${t.file}`, compactTopics: true });
  put('dist/windsurf/.windsurf/rules/ui-polish-kit.md', `${frontmatter({ trigger: bare('always_on'), description: 'UI polish core rules for any interface work.' })}\n${windsurfCore}`);
  for (const t of topics) {
    put(`dist/windsurf/.windsurf/rules/ui-polish-${t.file}`, `${frontmatter({ trigger: bare('model_decision'), description: `${t.title} rules (ui-polish-kit). ${t.when}` })}\n${digest(t, `${KIT}/rules/${t.file}`)}`);
  }
  put('dist/windsurf/.windsurf/rules/ui-polish-audit.md', `${frontmatter({ trigger: bare('model_decision'), description: `UI audit procedure (ui-polish-kit). ${SKILL_AUDIT}` })}\n${auditStub(KIT)}`);

  // --- Claude Code: plugin (repo root) and project-skill variant
  const skill = (kit, topicPath) => ({
    polish: `${frontmatter({ name: 'ui-polish', description: SKILL_POLISH })}\n${renderCore(root, topics, { kit, topicPath })}`,
    audit: `${frontmatter({ name: 'ui-audit', description: SKILL_AUDIT, 'argument-hint': '[path or URL to audit]' })}\n${auditStub(kit)}\nIf arguments were given, they name the scope: $ARGUMENTS`,
  });
  const pluginKit = '${CLAUDE_PLUGIN_ROOT}';
  const plugin = skill(pluginKit, (t) => `${pluginKit}/rules/${t.file}`);
  put('skills/ui-polish/SKILL.md', plugin.polish);
  put('skills/ui-audit/SKILL.md', plugin.audit);
  const project = skill(KIT, (t) => `${KIT}/rules/${t.file}`);
  put('dist/claude-project/.claude/skills/ui-polish/SKILL.md', project.polish);
  put('dist/claude-project/.claude/skills/ui-audit/SKILL.md', project.audit);

  put('.claude-plugin/plugin.json', JSON.stringify({
    name: 'ui-polish-kit',
    displayName: 'UI Polish Kit',
    version: pkg.version,
    description: pkg.description,
    author: { name: 'ui-polish-kit contributors' },
    license: 'MIT',
    keywords: ['ui', 'ux', 'design', 'frontend', 'audit', 'accessibility', 'tailwind', 'shadcn'],
  }, null, 2));
  put('.claude-plugin/marketplace.json', JSON.stringify({
    name: 'ui-polish-kit',
    description: 'Rules, recipes and an audit that stop coding agents from shipping generic, unfinished UI.',
    owner: { name: 'ui-polish-kit contributors' },
    plugins: [{ name: 'ui-polish-kit', source: './', description: pkg.description }],
  }, null, 2));

  validateOutputs(out);
  return { topics, outputs: out };
}

/** Structural checks on what is about to be written. Throws with every problem listed. */
export function validateOutputs(out) {
  const problems = [];
  for (const [rel, content] of out) {
    if (/\{\{\w+\}\}/.test(content)) problems.push(`${rel}: unreplaced {{placeholder}}`);
    if (rel.endsWith('.json')) { try { JSON.parse(content); } catch (e) { problems.push(`${rel}: invalid JSON (${e.message})`); } }
    const fm = /^---\n([\s\S]*?)\n---\n/.exec(content);
    if (/\.(mdc)$/.test(rel) || /SKILL\.md$/.test(rel) || rel.includes('.windsurf/')) {
      if (!fm) { problems.push(`${rel}: missing frontmatter`); continue; }
    }
    if (rel.endsWith('.mdc')) {
      if (!/^description: ".+"$/m.test(fm[1])) problems.push(`${rel}: needs a description`);
      if (!/^alwaysApply: (true|false)$/m.test(fm[1])) problems.push(`${rel}: needs alwaysApply: true|false`);
      if (content.split('\n').length > LIMITS.cursorLines) problems.push(`${rel}: over ${LIMITS.cursorLines} lines`);
    }
    if (rel.includes('.windsurf/')) {
      if (!/^trigger: (always_on|model_decision|glob|manual)$/m.test(fm[1])) problems.push(`${rel}: needs a valid trigger`);
      if (/^trigger: model_decision$/m.test(fm[1]) && !/^description: ".+"$/m.test(fm[1])) problems.push(`${rel}: model_decision rules need a description`);
      if (content.length > LIMITS.windsurfFile) problems.push(`${rel}: ${content.length} characters, over the ${LIMITS.windsurfFile} Windsurf per-file budget`);
    }
    if (/SKILL\.md$/.test(rel)) {
      const d = /^description: "(.+)"$/m.exec(fm[1]);
      if (!/^name: "[a-z][a-z0-9-]*"$/m.test(fm[1])) problems.push(`${rel}: needs a kebab-case name`);
      if (!d) problems.push(`${rel}: needs a description`);
      else if (d[1].length > LIMITS.skillDescription) problems.push(`${rel}: description over ${LIMITS.skillDescription} characters`);
      if (content.split('\n').length > 500) problems.push(`${rel}: over 500 lines`);
    }
    if (/(AGENTS|GEMINI)\.md$|copilot-instructions\.md$/.test(rel)) {
      if (!content.startsWith(MARK_START) || !content.trimEnd().endsWith(MARK_END)) problems.push(`${rel}: must be wrapped in the ui-polish-kit markers`);
      if (Buffer.byteLength(content) > LIMITS.codexBytes) problems.push(`${rel}: over Codex's 32 KiB project-doc limit`);
    }
    if (/(AGENTS|GEMINI)\.md$|copilot-instructions\.md$|ui-polish-kit\.mdc$|SKILL\.md$/.test(rel) && content.length > LIMITS.alwaysOn) {
      problems.push(`${rel}: ${content.length} characters; entry files must stay under ${LIMITS.alwaysOn}`);
    }
  }
  if (problems.length) throw new Error(`Generated output is malformed:\n  - ${problems.join('\n  - ')}`);
}

/** Files under generated directories that the build no longer produces. */
function staleFiles(root, out) {
  const stale = [];
  const visit = (rel) => {
    const abs = path.join(root, rel);
    if (!fs.existsSync(abs)) return;
    for (const e of fs.readdirSync(abs, { withFileTypes: true })) {
      const r = `${rel}/${e.name}`;
      if (e.isDirectory()) visit(r);
      else if (!out.has(r)) stale.push(r);
    }
  };
  visit('dist');
  visit('skills');
  return stale;
}

export function main(argv = process.argv.slice(2)) {
  const check = argv.includes('--check');
  let built;
  try {
    built = buildOutputs(ROOT);
  } catch (err) {
    console.error(`build failed: ${err.message}`);
    return 1;
  }
  const { topics, outputs } = built;
  const stale = staleFiles(ROOT, outputs);

  if (check) {
    const diffs = [];
    for (const [rel, content] of outputs) {
      const abs = path.join(ROOT, rel);
      if (!fs.existsSync(abs)) diffs.push(`missing: ${rel}`);
      else if (fs.readFileSync(abs, 'utf8').replace(/\r\n/g, '\n') !== content) diffs.push(`stale:   ${rel}`);
    }
    for (const s of stale) diffs.push(`orphan:  ${s}`);
    if (diffs.length) {
      console.error(`Generated files are out of date. Run \`npm run build\` and commit the result.\n  ${diffs.join('\n  ')}`);
      return 1;
    }
    console.log(`build check: ${outputs.size} generated files are up to date.`);
    return 0;
  }

  for (const s of stale) fs.rmSync(path.join(ROOT, s));
  for (const [rel, content] of outputs) {
    const abs = path.join(ROOT, rel);
    fs.mkdirSync(path.dirname(abs), { recursive: true });
    fs.writeFileSync(abs, content);
  }
  const ruleCount = topics.reduce((n, t) => n + t.rules.length, 0);
  const staticCount = topics.reduce((n, t) => n + t.rules.filter((r) => r.check === 'static').length, 0);
  console.log(`Built ${outputs.size} files from ${topics.length} topics, ${ruleCount} rules (${staticCount} checked statically).`);
  const groups = {};
  for (const rel of outputs.keys()) {
    const key = rel.startsWith('dist/') ? rel.split('/').slice(0, 2).join('/') : rel.split('/')[0];
    groups[key] = (groups[key] || 0) + 1;
  }
  for (const [k, n] of Object.entries(groups)) console.log(`  ${k.padEnd(22)} ${n} file${n === 1 ? '' : 's'}`);
  if (stale.length) console.log(`  removed ${stale.length} orphaned file(s)`);
  return 0;
}

if (process.argv[1] && import.meta.url === pathToFileURL(process.argv[1]).href) {
  process.exitCode = main();
}
